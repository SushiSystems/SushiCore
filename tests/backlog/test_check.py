"""Tests the rules `backlog check` enforces."""

from __future__ import annotations

from pathlib import Path

import pytest

from sushicore.backlog import BacklogStore, check_backlog
from sushicore.backlog.store import BacklogConfig

pytestmark = pytest.mark.medium


def _messages(store: BacklogStore, open_designs=lambda: ()) -> list[str]:
    """Returns the message of every fault."""
    return [fault.message for fault in check_backlog(store, open_designs)]


def _work(editor, **changes):
    """Adds a work entry with default values."""
    values = dict(area="PHYSICS", priority="P2", title="Fix the step", done_when="it passes")
    values.update(changes)
    return editor.add_work(**values)


def test_a_store_the_tool_wrote_is_clean(editor, store):
    """Every command leaves the store clean."""
    _work(editor)
    editor.add_issue(area="BUILD", origin="toolchain", symptom="The link fails", workaround="none")
    assert _messages(store) == []


def test_a_repository_without_a_store_is_clean_unless_it_holds_the_retired_files(tmp_path: Path):
    """The retired files send a repository to `import`."""
    assert check_backlog(BacklogStore(tmp_path)) == []
    retired = tmp_path / "docs" / "design" / "REMAINING_WORK.md"
    retired.parent.mkdir(parents=True)
    retired.write_text("# Remaining work\n", encoding="utf-8")
    assert "backlog import" in _messages(BacklogStore(tmp_path))[0]


def test_a_hand_edit_that_changes_the_shape_is_a_fault(editor, store):
    """A file the tool would not write fails."""
    _work(editor)
    path = store.area_path("PHYSICS")
    path.write_text(path.read_text(encoding="utf-8").replace("| RW-1 |", "|RW-1|"), encoding="utf-8")
    assert any("shape the tool writes" in message for message in _messages(store))


def test_a_duplicate_id_and_an_id_past_the_counter_are_faults(editor, store):
    """Two branches that took one number are sent to `renumber`."""
    _work(editor)
    path = store.area_path("PHYSICS")
    text = path.read_text(encoding="utf-8")
    row = next(line for line in text.splitlines() if line.startswith("| RW-1 "))
    path.write_text(text.replace(row, f"{row}\n{row.replace('RW-1', 'RW-7')}"), encoding="utf-8")
    store.write_area(store.read_area("PHYSICS"))
    found = _messages(store)
    assert any("past the counter" in message for message in found)


def test_a_missing_source_and_a_reference_to_no_entry_are_faults(editor, store):
    """Paths exist and IDs name open entries."""
    _work(editor, source="docs/design/README.md")
    _work(editor, blocked_by="RW-1")
    (store.root / "docs" / "design" / "README.md").write_text("# Design\n", encoding="utf-8")
    assert _messages(store) == []
    (store.root / "docs" / "design" / "README.md").unlink()
    assert any("does not exist" in message for message in _messages(store))


def test_a_blocked_entry_whose_blocks_closed_must_be_opened(editor, store):
    """A block on a closed entry is stale."""
    _work(editor)
    _work(editor, blocked_by="RW-1")
    area = store.read_area("PHYSICS")
    area.drop("RW-1")
    store.write_area(area)
    store.write_index()
    assert any("set State to open" in message for message in _messages(store))


def test_a_pin_on_a_closed_entry_is_a_fault(editor, store):
    """Pins name open work."""
    store.write_config(BacklogConfig(store.config().areas, ("RW-9",)))
    store.write_index()
    assert any("names no open work" in message for message in _messages(store))


def test_a_stale_index_and_an_orphan_detail_are_faults(editor, store):
    """The index is regenerated by every command; a detail belongs to an open entry."""
    _work(editor)
    (store.folder / "README.md").write_text("# Backlog\n", encoding="utf-8")
    store.write_detail("RW-5", "# RW-5\n")
    found = _messages(store)
    assert any("stale" in message for message in found)
    assert any("RW-5 is closed" in message for message in found)


def test_an_open_design_no_entry_cites_is_a_fault(editor, store):
    """Each open design is reached by work."""
    topic = store.root / "docs" / "design" / "PHYSICS" / "README.md"
    topic.parent.mkdir(parents=True)
    topic.write_text("# Physics\n", encoding="utf-8")
    assert any("open design topic" in message for message in _messages(store, lambda: [topic]))
    _work(editor, source="docs/design/PHYSICS/README.md")
    assert _messages(store, lambda: [topic]) == []


def test_a_file_the_store_does_not_know_is_a_fault(editor, store):
    """Only the configured areas live in docs/backlog."""
    (store.folder / "NOTES.md").write_text("# Notes\n", encoding="utf-8")
    assert any("not a file of the store" in message for message in _messages(store))
