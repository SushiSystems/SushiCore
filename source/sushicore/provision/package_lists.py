"""Keeps a list of package names free of repeats."""

from __future__ import annotations

def dedup(items: list[str]) -> list[str]:
    """Return *items* with duplicates removed, keeping first-seen order."""
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out
